def segmentation_prompt(numbered_doc: str, explicit_ids: list[str]) -> str:
    ids = ", ".join(explicit_ids) if explicit_ids else "(не найдено)"
    return f"""Задача: выдели из документа все отдельные проверяемые требования (единицы анализа).

Что считать требованием: любое утверждение, задающее поведение, свойство, ограничение, данные,
интерфейс, интеграцию, правило, критерий приёмки или параметр API — в любой части документа
(функциональные и нефункциональные требования, цели, архитектура, UI, схемы процессов, sequence,
требования к данным и интеграции, критерии приёмки (каждая строка таблицы — отдельно), шаги логики
метода, особые правила, параметры запроса/ответа, коды статусов, общие параметры API).
Не выделяй как требования: служебные пояснения о самом документе, шапку таблиц, пустые подписи.
Раздел ревью/согласований и пустые разделы НЕ выделяй как требования — они оцениваются на уровне набора.

Правила:
- Сохраняй исходную нарезку документа: пункт с собственным идентификатором (например, «Ф-1») — одна
  единица, даже если внутри несколько утверждений (атомарность проверим позже). Не дроби и не склеивай
  пункты с идентификаторами.
- Пункты без идентификатора: одна логически цельная фраза/строка таблицы/шаг = одна единица.
  Строки таблицы параметров API (один параметр = одна строка) можно объединить в одну единицу на таблицу,
  если в строках нет самостоятельных правил; коды ответов — по одной единице на код.
- doc_id — идентификатор из документа как есть (например «Ф-2», «Шаг 3», «Правило 1»), если он явно
  есть в тексте (номер пункта списка тоже годится: «Логика работы метода, п. 4»). Иначе null.
- quote — ДОСЛОВНАЯ цитата требования из документа (без префикса строк), до 300 символов; если пункт
  длиннее — его начало.
- line_start/line_end — номера строк (числа после L).
- summary — краткая формулировка сути (до 15 слов).
- kind — одно из: функциональное, нефункциональное, данные, интеграция, интерфейс, процесс,
  архитектура, цель, критерий приёмки, API, ограничение.
- Порядок — как в документе. Не пропускай требования из любой части документа.

Явные идентификаторы, найденные парсером (все должны присутствовать в ответе): {ids}

Схема ответа:
{{"requirements": [{{"doc_id": "Ф-1" | null, "section": "Часть A / Функциональные требования",
  "line_start": 37, "line_end": 37, "quote": "...", "summary": "...", "kind": "функциональное"}}]}}

Документ:
<<<
{numbered_doc}
>>>"""


