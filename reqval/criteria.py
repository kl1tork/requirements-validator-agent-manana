ALL = {c.code: c for c in INDIVIDUAL + SET}
INDIVIDUAL_CODES = [c.code for c in INDIVIDUAL]
SET_CODES = [c.code for c in SET]

SEVERITIES = {
    "critical": "Критично",
    "major": "Существенно",
    "minor": "Незначительно",
}
SEVERITY_ORDER = {"critical": 0, "major": 1, "minor": 2}

# Классы «критичных дефектов» из ТЗ: непроверяемые, противоречивые, неполные.
CRITICAL_CLASSES = {
    "Непроверяемые": {"verifiable", "set_validatable"},
    "Противоречивые": {"set_consistent", "correct"},
    "Неполные": {"complete", "set_complete"},
}


def name(code: str) -> str:
    c = ALL.get(code)
    return c.name if c else code


def ref(code: str) -> str:
    c = ALL.get(code)
    return c.ref if c else ""


def criteria_block(items: list[Criterion]) -> str:
    return "\n".join(f"- `{c.code}` — {c.name} ({c.ref}): {c.question}" for c in items)
